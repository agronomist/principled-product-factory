class BOMDependencyItem(BaseModel):
    """Bill-of-Materials entry linking a product to its foundation model & API cost structure."""

    model_config = ConfigDict(extra="forbid", frozen=True)

    product_slug: str = Field(..., min_length=1)
    primary_model_provider: str = Field(..., min_length=1)
    secondary_distilled_provider: str = Field(..., min_length=1)
    baseline_economics: UnitEconomicsInput = Field(...)


class PortfolioMarginShockReport(BaseModel):
    """Portfolio-wide impact report when an upstream model supplier hikes inference prices."""

    model_config = ConfigDict(extra="forbid", frozen=True)

    shocked_provider: str = Field(..., min_length=1)
    price_multiplier: float = Field(..., gt=0.0)
    affected_products: tuple[str, ...] = Field(...)
    products_requiring_distillation_switch: tuple[str, ...] = Field(...)
    products_blocked_even_after_distillation: tuple[str, ...] = Field(...)
    portfolio_resilient: bool = Field(...)


class SupplyChainBOMRegistry:
    """Tracks multi-product dependencies and simulates upstream vendor price shocks (Porter's
    Five Forces: Supplier Power).
    """

    def __init__(self, margin_gate: ContributionMarginGate | None = None) -> None:
        self._gate = margin_gate or ContributionMarginGate()
        self._items: dict[str, BOMDependencyItem] = {}

    def register_product_bom(self, item: BOMDependencyItem) -> None:
        self._items[item.product_slug] = item

    def simulate_supplier_price_shock(
        self,
        provider_name: str,
        inference_price_multiplier: float,
    ) -> PortfolioMarginShockReport:
        """Simulate an `inference_price_multiplier` shock on `provider_name` across all products."""
        if inference_price_multiplier <= 0.0:
            raise ValueError("inference_price_multiplier must be > 0.")

        affected: list[str] = []
        distill_switch: list[str] = []
        hard_blocked: list[str] = []

        for slug, item in sorted(self._items.items()):
            if item.primary_model_provider != provider_name:
                continue
            affected.append(slug)
            shocked_econ = item.baseline_economics.model_copy(
                update={
                    "inference_cost": item.baseline_economics.inference_cost
                    * inference_price_multiplier
                }
            )
            res = self._gate.evaluate(shocked_econ)
            if not res.passed:
                if res.decision.value == "downgrade_to_distilled":
                    distill_switch.append(slug)
                else:
                    hard_blocked.append(slug)

        return PortfolioMarginShockReport(
            shocked_provider=provider_name,
            price_multiplier=inference_price_multiplier,
            affected_products=tuple(affected),
            products_requiring_distillation_switch=tuple(distill_switch),
            products_blocked_even_after_distillation=tuple(hard_blocked),
            portfolio_resilient=(len(hard_blocked) == 0),
        )


