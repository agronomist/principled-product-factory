class CanaryStageMetrics(BaseModel):
    """Live telemetry observed at a progressive canary traffic stage (`1%`, `10%`, `50%`, `100%`)."""

    model_config = ConfigDict(extra="forbid", frozen=True)

    traffic_percentage: int = Field(..., ge=1, le=100)
    observed_p99_latency_ms: float = Field(..., gt=0.0)
    observed_control_arm_count: int = Field(..., ge=1)
    observed_canary_arm_count: int = Field(..., ge=1)
    expected_canary_ratio: float = Field(..., gt=0.0, lt=1.0)
    live_unit_economics: UnitEconomicsInput = Field(...)


class CanaryStageStatus(str, Enum):
    """Canary stage progression verdicts."""

    PROMOTED_TO_NEXT_STAGE = "promoted_to_next_stage"
    GRADUATED_100_PERCENT = "graduated_100_percent"
    ROLLED_BACK_ON_SHEWHART_BREACH = "rolled_back_on_shewhart_breach"
    ROLLED_BACK_ON_SRM_MISMATCH = "rolled_back_on_srm_mismatch"
    ROLLED_BACK_ON_MARGIN_LEAKAGE = "rolled_back_on_margin_leakage"


class CanaryStageDecision(BaseModel):
    """Immutable decision from evaluating a progressive canary stage."""

    model_config = ConfigDict(extra="forbid", frozen=True)

    release_id: str = Field(..., min_length=1)
    evaluated_stage_pct: int = Field(...)
    next_stage_pct: int = Field(..., ge=0, le=100)
    status: CanaryStageStatus = Field(...)
    rolled_back: bool = Field(...)
    post_mortem_fixture: RegressionFixture | None = Field(default=None)
    explanation: str = Field(..., min_length=1)


class CanaryRolloutController:
    r"""Enforces progressive delivery (`1% -> 10% -> 50% -> 100%`) gated on Shewhart $\pm 3\sigma$,
    Sample Ratio Mismatch ($\chi^2$ $p \ge 0.01$), and real-time Contribution Margin.

    Any breach automatically rolls traffic back to `0%` and generates a minimized
    `RegressionFixture` via `BlamelessPostMortem`.
    """

    CANONICAL_STAGES: tuple[int, ...] = (1, 10, 50, 100)

    def __init__(
        self,
        latency_monitor: ShewhartMonitor | None = None,
        margin_gate: ContributionMarginGate | None = None,
        post_mortem: BlamelessPostMortem | None = None,
    ) -> None:
        self._latency_monitor = latency_monitor or ShewhartMonitor(
            metric_name="p99_latency_ms",
            baseline_mean=120.0,
            baseline_std=20.0,
            sigma_multiplier=3.0,
        )
        self._margin_gate = margin_gate or ContributionMarginGate()
        self._post_mortem = post_mortem or BlamelessPostMortem()

    def evaluate_stage(
        self,
        release_id: str,
        metrics: CanaryStageMetrics,
    ) -> CanaryStageDecision:
        # 1. Check Shewhart +/- 3-sigma latency control limit
        if self._latency_monitor.is_breach(metrics.observed_p99_latency_ms):
            fixture = self._post_mortem.generate_fixture(
                IncidentEvent(
                    incident_id=f"CANARY-{release_id}-{metrics.traffic_percentage}PCT",
                    severity="SHEWHART_3SIGMA",
                    node_id=f"canary_stage_{metrics.traffic_percentage}pct",
                    metric_name="p99_latency_ms",
                    observed_value=metrics.observed_p99_latency_ms,
                    baseline_mean=self._latency_monitor.baseline_mean,
                    baseline_std=self._latency_monitor.baseline_std,
                    sigma_limit=self._latency_monitor.sigma_multiplier,
                    raw_input_payload={
                        "release_id": release_id,
                        "traffic_pct": metrics.traffic_percentage,
                        "debug_trace": "stripped_by_minimizer",
                    },
                    failure_exception_type="CanaryLatency3SigmaBreach",
                    failure_message=(
                        f"Canary p99 latency {metrics.observed_p99_latency_ms}ms exceeded "
                        f"UCL {self._latency_monitor.upper_control_limit}ms."
                    ),
                    expected_safe_fallback_tier=FallbackTier.SECONDARY_DISTILLED_MODEL,
                )
            )
            return CanaryStageDecision(
                release_id=release_id,
                evaluated_stage_pct=metrics.traffic_percentage,
                next_stage_pct=0,
                status=CanaryStageStatus.ROLLED_BACK_ON_SHEWHART_BREACH,
                rolled_back=True,
                post_mortem_fixture=fixture,
                explanation=fixture.blameless_root_cause_summary,
            )

        # 2. Check Sample Ratio Mismatch (SRM chi-square p >= 0.01) against expected split
        srm_res = compute_srm_chi_square(
            observed_counts=(
                metrics.observed_control_arm_count,
                metrics.observed_canary_arm_count,
            ),
            expected_ratios=(
                1.0 - metrics.expected_canary_ratio,
                metrics.expected_canary_ratio,
            ),
        )
        if srm_res.srm_detected:
            return CanaryStageDecision(
                release_id=release_id,
                evaluated_stage_pct=metrics.traffic_percentage,
                next_stage_pct=0,
                status=CanaryStageStatus.ROLLED_BACK_ON_SRM_MISMATCH,
                rolled_back=True,
                post_mortem_fixture=None,
                explanation=(
                    f"Rolled back canary '{release_id}' at {metrics.traffic_percentage}%: "
                    f"Sample Ratio Mismatch detected (p={srm_res.p_value:.6f} < 0.01)."
                ),
            )

        # 3. Check live unit Contribution Margin Gate
        margin_res = self._margin_gate.evaluate(metrics.live_unit_economics)
        if not margin_res.passed:
            return CanaryStageDecision(
                release_id=release_id,
                evaluated_stage_pct=metrics.traffic_percentage,
                next_stage_pct=0,
                status=CanaryStageStatus.ROLLED_BACK_ON_MARGIN_LEAKAGE,
                rolled_back=True,
                post_mortem_fixture=None,
                explanation=(
                    f"Rolled back canary '{release_id}' at {metrics.traffic_percentage}%: "
                    f"Live unit contribution margin failed ({margin_res.explanation})."
                ),
            )

        # All 3 gates passed! Advance to next stage in CANONICAL_STAGES
        if metrics.traffic_percentage >= 100:
            return CanaryStageDecision(
                release_id=release_id,
                evaluated_stage_pct=100,
                next_stage_pct=100,
                status=CanaryStageStatus.GRADUATED_100_PERCENT,
                rolled_back=False,
                post_mortem_fixture=None,
                explanation=f"Release '{release_id}' graduated to 100% general availability.",
            )

        higher_stages = [
            s for s in self.CANONICAL_STAGES if s > metrics.traffic_percentage
        ]
        next_pct = higher_stages[0] if higher_stages else 100
        return CanaryStageDecision(
            release_id=release_id,
            evaluated_stage_pct=metrics.traffic_percentage,
            next_stage_pct=next_pct,
            status=CanaryStageStatus.PROMOTED_TO_NEXT_STAGE,
            rolled_back=False,
            post_mortem_fixture=None,
            explanation=(
                f"Canary stage {metrics.traffic_percentage}% healthy (p99={metrics.observed_p99_latency_ms}ms, "
                f"SRM p={srm_res.p_value:.4f}, margin=${margin_res.contribution_margin:.4f}); "
                f"promoting to {next_pct}%."
            ),
        )


