r"""Industrial Software Factory Floor Substrate (`platform/factory_floor/operations.py`).

Completes the five classic & modern "Factory Floor" components (Hitachi *Kojo*, Cusumano,
Greenfield & Short *Software Factories*, StrongDM Dark Factory Holdout Twins, and Eliyahu
Goldratt's *Theory of Constraints* / OEE):

1. **`ProductLineStampingPress` & `RuleOfTwoASTHarvester` (The Stamping Press)**:
   - Stamps out a complete, runnable new product line under `products/<product-slug>/`
     (`skills/`, `workflows/factory_dag.yaml`, `evals/golden_cases.jsonl`, `features/README.md`)
     only when a `CustomerEvidenceArtifact` passes `BuildTrapGate`.
   - `RuleOfTwoASTHarvester` scans AST function signatures and normalized bodies across all
     vertical products under `products/*`. When $\ge 2$ products implement structurally
     duplicate logic, it flags a `CrossProductDuplicationFinding` naming the exact `platform/`
     target module for extraction (`principle-build-the-lever` & Law 2 Rule-of-Two).

2. **`SupplyChainBOMRegistry` (Raw Materials Warehouse & Porter Supplier-Shock Simulator)**:
   - Tracks the Bill of Materials (foundation model providers, token prices, data APIs) consumed
     by every product in the portfolio.
   - Simulates upstream vendor price shocks (e.g., a 3x frontier token price hike) across all
     products simultaneously and prescribes automatic distillation switches before unit
     contribution margin bleeds.

3. **`HoldoutDigitalTwin` (The Wind Tunnel / Dark-Factory Sealed Holdout Replay)**:
   - Stores sealed shadow-traffic scenarios *outside* the implementer station's repository read
     path so coding agents cannot overfit to `golden_cases.jsonl` (Goodhart's Law protection).
   - Replays candidate skills against the sealed holdout set and verifies Liskov postconditions
     and unit cost ceilings before canary deployment.

4. **`CanaryRolloutController` (The Loading Dock: `1% -> 10% -> 50% -> 100%`)**:
   - Governs post-merge progressive delivery across 4 traffic stages (`1% -> 10% -> 50% -> 100%`).
   - At every stage, verifies:
     * Shewhart $\pm 3\sigma$ latency/error control limits (`ShewhartMonitor`),
     * Sample Ratio Mismatch chi-square check ($p \ge 0.01$, `compute_srm_chi_square`), and
     * Live Contribution Margin Gate (`ContributionMarginGate`).
   - On any breach, immediately halts the ramp, auto-reverts to stable (`0%`), and compiles a
     minimized JSON regression fixture via `BlamelessPostMortem`.

5. **`FactoryOEEMonitor` (Overall Equipment Effectiveness & Goldratt Theory of Constraints)**:
   - Computes industrial OEE across the software factory floor:
     $$\text{OEE} = \text{Availability} \times \text{Performance} \times \text{FirstPassYield}$$
   - Tracks **First-Pass Yield (FPY)** (fraction of Foreman runs approved by the cross-vendor
     reviewer on Round 0 without rework), **Scrap & Rework Cost Ratio**, and identifies the
     exact **Bottleneck Station** (highest utilization $\rho$ / cycle time $W$) per Goldratt's
     Theory of Constraints.
"""

