class HoldoutScenario(BaseModel):
    """A sealed shadow-traffic scenario stored outside the implementer agent's repo view."""

    model_config = ConfigDict(extra="forbid", frozen=True)

    scenario_id: str = Field(..., min_length=1)
    shadow_input: dict[str, Any] = Field(...)
    expected_invariant_key: str = Field(..., min_length=1)
    expected_invariant_value: Any = Field(...)
    max_acceptable_cost_usd: float = Field(..., gt=0.0)


class HoldoutReplayResult(BaseModel):
    """Verification report from replaying sealed holdout traffic against a candidate build."""

    model_config = ConfigDict(extra="forbid", frozen=True)

    total_scenarios: int = Field(..., ge=1)
    passed_scenarios: int = Field(..., ge=0)
    pass_rate: float = Field(..., ge=0.0, le=1.0)
    failed_scenario_ids: tuple[str, ...] = Field(...)
    approved_for_canary: bool = Field(...)


class HoldoutDigitalTwin:
    """Sealed holdout evaluator preventing coding agents from overfitting to repo-visible tests."""

    def __init__(self, scenarios: Sequence[HoldoutScenario]) -> None:
        if not scenarios:
            raise ValueError("HoldoutDigitalTwin requires at least 1 sealed scenario.")
        self._scenarios = tuple(scenarios)

    def replay_shadow_traffic(
        self,
        candidate_fn: Callable[[dict[str, Any]], dict[str, Any]],
    ) -> HoldoutReplayResult:
        passed = 0
        failed_ids: list[str] = []

        for sc in self._scenarios:
            out = candidate_fn(sc.shadow_input)
            actual_val = out.get(sc.expected_invariant_key)
            actual_cost = float(out.get("cost_usd", 0.0))
            if (
                actual_val == sc.expected_invariant_value
                and actual_cost <= sc.max_acceptable_cost_usd + 1e-9
            ):
                passed += 1
            else:
                failed_ids.append(sc.scenario_id)

        total = len(self._scenarios)
        return HoldoutReplayResult(
            total_scenarios=total,
            passed_scenarios=passed,
            pass_rate=round(passed / total, 4),
            failed_scenario_ids=tuple(failed_ids),
            approved_for_canary=(passed == total),
        )


