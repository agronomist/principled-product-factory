class StampedProductManifest(BaseModel):
    """Immutable manifest of files generated by `ProductLineStampingPress`."""

    model_config = ConfigDict(extra="forbid", frozen=True)

    product_slug: str = Field(..., min_length=3, pattern=r"^[a-z0-9-]+$")
    product_dir: str = Field(..., min_length=1)
    created_files: tuple[str, ...] = Field(..., min_length=1)
    opportunity_score: float = Field(..., ge=10.0)


class ProductLineStampingPress:
    """Stamps out a new vertical product directory under `products/<product_slug>/`
    once customer demand passes `BuildTrapGate`.
    """

    def __init__(self, build_trap_gate: BuildTrapGate | None = None) -> None:
        self._gate = build_trap_gate or BuildTrapGate()

    def stamp_product(
        self,
        products_root: Path,
        product_slug: str,
        customer_evidence: CustomerEvidenceArtifact,
    ) -> StampedProductManifest:
        if not re.fullmatch(r"^[a-z0-9]+(?:-[a-z0-9]+)*$", product_slug):
            raise ValueError(f"Invalid product_slug: {product_slug!r}")

        verdict = self._gate.check_or_raise(customer_evidence)
        product_dir = products_root / product_slug
        skills_dir = product_dir / "skills"
        workflows_dir = product_dir / "workflows"
        evals_dir = product_dir / "evals"
        features_dir = product_dir / "features"

        for d in (skills_dir, workflows_dir, evals_dir, features_dir):
            d.mkdir(parents=True, exist_ok=True)

        init_file = product_dir / "__init__.py"
        init_file.write_text(
            f'"""Stamped vertical product line: {product_slug}."""\n',
            encoding="utf-8",
        )

        skills_init = skills_dir / "__init__.py"
        skills_init.write_text(
            f'"""Domain skills for {product_slug}."""\n',
            encoding="utf-8",
        )

        dag_file = workflows_dir / "factory_dag.yaml"
        dag_file.write_text(
            f'workflow_id: "{product_slug}-v1"\n'
            f'version: "10.0.0"\n'
            f'lifecycle_stage: "{customer_evidence.lifecycle_stage}"\n'
            f"wip_limit: 5\n"
            f"nodes:\n"
            f'  - node_id: "validate_margin_gate"\n'
            f'    description: "Pre-flight Contribution Margin Gate"\n'
            f"    dependencies: []\n"
            f'    skill_ref: "platform.metering.margin_guard"\n'
            f'    compensating_action: "release_margin_reservation"\n',
            encoding="utf-8",
        )

        golden_file = evals_dir / "golden_cases.jsonl"
        golden_case = {
            "case_id": f"{product_slug}-case-01",
            "description": customer_evidence.jtbd.desired_customer_outcome,
            "lifecycle_stage": customer_evidence.lifecycle_stage,
            "expected_margin_passed": True,
        }
        golden_file.write_text(json.dumps(golden_case, sort_keys=True) + "\n", encoding="utf-8")

        feature_file = features_dir / "core-workflow.md"
        feature_file.write_text(
            f"# Feature: {customer_evidence.jtbd.desired_customer_outcome}\n\n"
            f"## Sub-features\n\n- {customer_evidence.jtbd.struggling_moment}\n\n"
            f"## How to get to it (user POV)\n\nRun `{product_slug}` workflow.\n\n"
            f"## Driving it with SubprocessCLIHarness\n\nExecute `--case-id {product_slug}-case-01`.\n\n"
            f"## Gotchas\n\nRequires ContributionMarginGate pass.\n",
            encoding="utf-8",
        )
        readme_file = features_dir / "README.md"
        readme_file.write_text(
            f"# `{product_slug}` Feature Map\n\n- [core-workflow.md](core-workflow.md)\n",
            encoding="utf-8",
        )

        created = (
            str(init_file),
            str(skills_init),
            str(dag_file),
            str(golden_file),
            str(feature_file),
            str(readme_file),
        )
        return StampedProductManifest(
            product_slug=product_slug,
            product_dir=str(product_dir),
            created_files=created,
            opportunity_score=verdict.jtbd_score.opportunity_score,
        )


class CrossProductDuplicationFinding(BaseModel):
    """Report of a function or primitive duplicated across >= 2 products (violating Rule-of-Two)."""

    model_config = ConfigDict(extra="forbid", frozen=True)

    function_name: str = Field(..., min_length=1)
    ast_signature_hash: str = Field(..., min_length=64, max_length=64)
    products_containing_duplicate: tuple[str, ...] = Field(..., min_length=2)
    extraction_prescription: str = Field(..., min_length=1)


class RuleOfTwoASTHarvester:
    """Scans ASTs across `products/<slug>/` to detect when >= 2 products implement structurally
    identical helper functions, enforcing Law 2 (Rule-of-Two extraction into `platform/`).
    """

    @staticmethod
    def _normalize_function_ast(fn_node: ast.FunctionDef) -> str:
        """Compute a canonical AST dump of a function body ignoring line numbers and docstrings."""
        body_stmts = list(fn_node.body)
        if (
            body_stmts
            and isinstance(body_stmts[0], ast.Expr)
            and isinstance(body_stmts[0].value, ast.Constant)
            and isinstance(body_stmts[0].value.value, str)
        ):
            body_stmts = body_stmts[1:]
        arg_names = [a.arg for a in fn_node.args.args]
        stmt_dumps = [ast.dump(s, include_attributes=False) for s in body_stmts]
        canonical = f"fn:{fn_node.name}|args:{arg_names}|body:{stmt_dumps}"
        return hashlib.sha256(canonical.encode("utf-8")).hexdigest()

    def scan_products_for_harvesting(
        self,
        products_by_slug: dict[str, str],
    ) -> tuple[CrossProductDuplicationFinding, ...]:
        """Compare Python source strings keyed by `product_slug` and flag Rule-of-Two duplicates."""
        seen_hashes: dict[tuple[str, str], list[str]] = {}

        for slug, source_code in sorted(products_by_slug.items()):
            tree = ast.parse(source_code, filename=slug)
            for node in ast.walk(tree):
                if isinstance(node, ast.FunctionDef) and not node.name.startswith("__"):
                    sig_hash = self._normalize_function_ast(node)
                    key = (node.name, sig_hash)
                    slugs = seen_hashes.setdefault(key, [])
                    if slug not in slugs:
                        slugs.append(slug)

        findings: list[CrossProductDuplicationFinding] = []
        for (fn_name, sig_hash), slugs in sorted(seen_hashes.items()):
            if len(slugs) >= 2:
                findings.append(
                    CrossProductDuplicationFinding(
                        function_name=fn_name,
                        ast_signature_hash=sig_hash,
                        products_containing_duplicate=tuple(slugs),
                        extraction_prescription=(
                            f"Rule-of-Two triggered: function '{fn_name}' is duplicated across "
                            f"products {slugs}. FIX: Extract '{fn_name}' into a shared module under "
                            "'platform/' behind a frozen Pydantic v2 contract and delete the product copies."
                        ),
                    )
                )
        return tuple(findings)


